double _distSq(double lat1, double lon1, double lat2, double lon2) {
  // 위도 1도 ≈ 111km, 경도는 위도에 따라 보정한 근사 거리 비교용
  final dLat = lat1 - lat2;
  final dLon = (lon1 - lon2) * math.cos(lat1 * math.pi / 180);
  return dLat * dLat + dLon * dLon;
}

/// 장소마다 가장 가까운 조위관측소를 찾아 [Station] 목록으로 변환한다.
List<Station> resolvePlaces(List<Station> tideStations) {
  if (tideStations.isEmpty) return const [];
  final out = <Station>[];
  for (var i = 0; i < rawPlaces.length; i++) {
    final p = rawPlaces[i];
    Station nearest = tideStations.first;
    var best = double.infinity;
    for (final s in tideStations) {
      final d = _distSq(p.lat, p.lon, s.lat, s.lon);
      if (d < best) {
        best = d;
        nearest = s;
      }
    }
    out.add(Station(
      id: 'P_$i-${p.name}',
      code: nearest.code,
      name: p.name,
      type: p.type,
      lat: p.lat,
      lon: p.lon,
    ));
  }
  return out;
}
